use std::mem::size_of;
use sniper_types::{grid_types::GridRiskState, l2_command::L2SharedState, moonshot_types::MoonshotRiskState, trigon_types::TrigonRiskState};

fn main() {
    let mut out = String::from("# AUTO-GENERATED BY RUST (dump_l2_offsets.rs) — DO NOT EDIT\n\n");
    
    out.push_str("# L2SharedState Offsets (l2_command.bin)\n");
    out.push_str(&format!("CL1_CMD_OFFSET = 0\n"));
    out.push_str(&format!("CL2_AS_OFFSET = {}\n", size_of::<sniper_types::l2_command::L2CommandMatrix>()));
    out.push_str(&format!("CL3_GRID_OFFSET = {}\n", size_of::<sniper_types::l2_command::L2CommandMatrix>() + size_of::<sniper_types::l2_command::L2ASMatrix>()));
    out.push_str(&format!("CL4_RISK_OFFSET = {}\n", size_of::<sniper_types::l2_command::L2CommandMatrix>() + size_of::<sniper_types::l2_command::L2ASMatrix>() + size_of::<sniper_types::l2_command::L2GridWarpMatrix>()));
    out.push_str(&format!("L2_TOTAL_SIZE = {}\n\n", size_of::<L2SharedState>()));

    out.push_str("# Specific Global Paused Offsets in Risk Mmaps\n");
    
    // Specific Global Paused Offsets
    out.push_str(&format!("MOONSHOT_PAUSED_OFFSET = {}\n", std::mem::offset_of!(MoonshotRiskState, global_paused)));
    out.push_str(&format!("GRID_PAUSED_OFFSET = {}\n", std::mem::offset_of!(GridRiskState, global_paused)));
    out.push_str(&format!("TRIGON_PAUSED_OFFSET = {}\n", std::mem::offset_of!(TrigonRiskState, global_paused)));

    // Write to architect folder
    out.push_str("\n# ML Shield Offsets (engine_state.bin)\n");
    out.push_str(&format!("OFF_L1_SKEW = {}\n", std::mem::offset_of!(sniper_types::EngineState, l1_skew_adjustment)));
    out.push_str(&format!("OFF_L1_CONF = {}\n", std::mem::offset_of!(sniper_types::EngineState, l1_confidence_score)));

    let out_path = std::env::current_dir()
        .unwrap_or_default()
        .join("architect/l2_rust_offsets.py");
    std::fs::write(&out_path, out).expect("Failed to write python offsets");
    println!("Successfully dumped L2 offsets to: {:?}", out_path);
}
